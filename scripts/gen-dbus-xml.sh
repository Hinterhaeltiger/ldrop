# Regenerates packaging/dbus/interfaces/org.ldrop.Ldrop1.xml by introspecting a simulated
# ldropd (and an `ldrop receive` agent) on a private session bus.
#
#   scripts/gen-dbus-xml.sh
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
out=$root/packaging/dbus/interfaces/org.ldrop.Ldrop1.xml

if [[ ${1:-} != --inner ]]; then
    cargo build --quiet --manifest-path "$root/Cargo.toml" -p ldropd -p ldrop-cli
    work=$(mktemp -d)
    trap 'rm -rf "$work"' EXIT
    WORK=$work timeout 60 dbus-run-session -- "$0" --inner
    python3 -I - "$work" "$out" <<'EOF'
import sys, xml.etree.ElementTree as ET
src, out = sys.argv[1], sys.argv[2]
wanted = ["org.ldrop.Ldrop1.Manager", "org.ldrop.Ldrop1.Discovery",
          "org.ldrop.Ldrop1.Transfer", "org.ldrop.Ldrop1.Agent"]
found = {}
for f in ["root.xml", "discovery.xml", "transfer.xml", "agent.xml"]:
    for iface in ET.parse(f"{src}/{f}").getroot().findall("interface"):
        if iface.get("name") in wanted:
            found[iface.get("name")] = iface
missing = [w for w in wanted if w not in found]
if missing:
    sys.exit(f"not found: {missing}")
node = ET.Element("node")
for w in wanted:
    node.append(found[w])
ET.indent(node, "  ")
header = ('<!DOCTYPE node PUBLIC "-//freedesktop//DTD D-BUS Object Introspection 1.0//EN"\n'
          ' "http://www.freedesktop.org/standards/dbus/1.0/introspect.dtd">\n'
          '<!-- SPDX-License-Identifier: GPL-3.0-or-later -->\n'
          '<!-- org.ldrop.Ldrop1 API (SPEC §10). Generated by scripts/gen-dbus-xml.sh; the Agent\n'
          '     interface is served by frontends (see ldrop-client). Do not edit by hand. -->\n')
open(out, "w").write(header + ET.tostring(node, encoding="unicode") + "\n")
EOF
    echo "wrote $out"
    exit 0
fi

# Inside the private bus.
bin=$root/target/debug
export XDG_CONFIG_HOME=$WORK/config XDG_STATE_HOME=$WORK/state
introspect() {
    busctl --user call "$1" "$2" org.freedesktop.DBus.Introspectable Introspect |
        sed 's/^s "//; s/"$//; s/\\"/"/g; s/\\n/\n/g' > "$WORK/$3"
}

"$bin/ldropd" --dev-sim 2> "$WORK/ldropd.log" &
daemon=$!
for _ in $(seq 50); do busctl --user status org.ldrop.Ldrop1 > /dev/null 2>&1 && break; sleep 0.1; done
introspect org.ldrop.Ldrop1 /org/ldrop/Ldrop1 root.xml

timeout 10 "$bin/ldrop" devices --watch < /dev/null > /dev/null 2>&1 &
sleep 0.5
introspect org.ldrop.Ldrop1 /org/ldrop/Ldrop1/discovery discovery-dir.xml
session=$(grep -o 'node name="[0-9]*"' "$WORK/discovery-dir.xml" | head -1 | grep -o '[0-9]*')
introspect org.ldrop.Ldrop1 "/org/ldrop/Ldrop1/discovery/$session" discovery.xml

transfer=$(busctl --user call org.ldrop.Ldrop1 /org/ldrop/Ldrop1 org.ldrop.Ldrop1.Debug \
    InjectIncoming ssast Peer android 1 a 1 | awk '{print $2}' | tr -d '"')
introspect org.ldrop.Ldrop1 "$transfer" transfer.xml

timeout 10 "$bin/ldrop" receive < /dev/zero > /dev/null 2>&1 &
for _ in $(seq 50); do grep -q "agent registered" "$WORK/ldropd.log" && break; sleep 0.1; done
agent=$(grep -o "agent registered: :[0-9.]*" "$WORK/ldropd.log" | awk '{print $3}')
introspect "$agent" /org/ldrop/client/agent0 agent.xml

kill "$daemon"
wait
